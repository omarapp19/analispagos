// Stub mínimo de Supabase (auth, storage, roles) + tablas del ERP con el tipo de id elegido.
export function stubSql(idType) {
  const idCol = {
    uuid: 'id uuid primary key default gen_random_uuid()',
    bigint: 'id bigint generated by default as identity primary key',
    text: "id text primary key default gen_random_uuid()::text",
  }[idType];
  const ref = { uuid: 'uuid', bigint: 'bigint', text: 'text' }[idType];
  return `
create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;
grant usage on schema public to anon, authenticated, service_role;
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema public grant execute on functions to anon, authenticated, service_role;

create schema auth;
grant usage on schema auth to anon, authenticated, service_role;
create table auth.users (id uuid primary key default gen_random_uuid(), email text unique);
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant execute on function auth.uid() to anon, authenticated, service_role;
grant select on auth.users to authenticated, service_role;

create schema storage;
grant usage on schema storage to anon, authenticated, service_role;
create table storage.buckets (id text primary key, name text, public boolean default false,
  file_size_limit bigint, allowed_mime_types text[]);
create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text references storage.buckets(id),
  name text, owner uuid, created_at timestamptz default now());
alter table storage.objects enable row level security;
grant all on storage.objects to anon, authenticated, service_role;
grant all on storage.buckets to service_role;
create function storage.foldername(name text) returns text[] language sql immutable as $$
  select (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'),1)-1] $$;
grant execute on function storage.foldername(text) to anon, authenticated;

-- Igual que la base real de producción: SIN "productType" (lo agrega la migración 0002b).
create table public.inventory (${idCol}, code text, name text, brand text, description text,
  quantity int default 0, "costPrice" numeric default 0, "marginPercentage" numeric default 0,
  "sellingPrice" numeric default 0, "taxPercentage" numeric default 16, "unitsPerPackage" int default 1,
  image text default '', "createdAt" timestamptz default now(),
  "updatedAt" timestamptz default now());
create table public.clients (${idCol}, name text, "documentId" text, phone text, email text, address text,
  "createdAt" timestamptz default now(), "updatedAt" timestamptz default now());
create table public.client_invoices (${idCol}, "invoiceNumber" text, "clientId" ${ref}, "clientName" text,
  items jsonb, subtotal numeric, total numeric, "isCredit" boolean default false, "creditDays" int default 0,
  status text, "paymentMethod" text, date text, "createdAt" timestamptz default now(), "updatedAt" timestamptz default now());
create table public.kardex (${idCol}, "productId" ${ref}, "productName" text, type text, quantity int,
  concept text, "user" text, date timestamptz default now());
create table public.transactions (${idCol}, amount numeric, method text, date text, note text, type text,
  category text, status text, "billId" ${ref}, "createdAt" timestamptz default now());
create table public.settings (id text primary key, data jsonb, "updatedAt" timestamptz);
create table public.users (${idCol}, username text, password text, role text);
create table public.bills (${idCol}, title text);
create table public.providers (${idCol}, name text);
create table public.investments (${idCol}, investor text);
create table public.recurring_expenses (${idCol}, concept text);
-- política vieja permisiva para authenticated (debe desaparecer con 0002)
alter table public.inventory enable row level security;
create policy "Enable all for authenticated" on public.inventory for all to authenticated using (true) with check (true);
create policy "Enable read for all" on public.clients for select using (true);
`;
}
