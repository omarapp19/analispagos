-- ---------- Ajuste de stock atómico y conteo físico ----------
-- Reemplaza el "leer, sumar y escribir" del navegador, que pisaba ventas simultáneas.
create or replace function public.erp_adjust_stock(p_product_id text, p_delta int, p_concept text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_prod record; v_user text; v_new int;
begin
  if not is_admin() then raise exception 'No autorizado' using errcode = '42501'; end if;
  if coalesce(p_delta, 0) = 0 then raise exception 'El ajuste no puede ser cero'; end if;
  if coalesce(btrim(p_concept), '') = '' then raise exception 'Indica el motivo del ajuste'; end if;
  select * into v_prod from inventory where id::text = p_product_id for update;
  if not found then raise exception 'Producto no encontrado'; end if;
  select username into v_user from staff_profiles where "userId" = auth.uid();
  v_new := greatest(coalesce(v_prod.quantity, 0) + p_delta, 0);
  update inventory set quantity = v_new, "updatedAt" = now() where id = v_prod.id;
  insert into kardex ("productId","productName",type,quantity,concept,"user")
  values (v_prod.id, v_prod.name, case when p_delta > 0 then 'ENTRADA' else 'SALIDA' end,
          abs(v_new - coalesce(v_prod.quantity, 0)), p_concept, coalesce(v_user,'Sistema'));
  perform audit_write('STOCK_ADJUST', 'inventory', v_prod.id::text,
    jsonb_build_object('name', v_prod.name, 'from', v_prod.quantity, 'to', v_new, 'concept', p_concept));
  return jsonb_build_object('id', v_prod.id::text, 'quantity', v_new);
end $$;

-- p_counts: [{"productId": "...", "counted": 12}]. Fija la existencia al conteo y deja kardex de cada diferencia.
create or replace function public.erp_apply_stock_count(p_counts jsonb, p_note text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_line record; v_prod record; v_user text; v_changed int := 0; v_diff int;
begin
  if not is_admin() then raise exception 'No autorizado' using errcode = '42501'; end if;
  if jsonb_typeof(p_counts) <> 'array' or jsonb_array_length(p_counts) = 0 then raise exception 'No hay conteos'; end if;
  select username into v_user from staff_profiles where "userId" = auth.uid();
  for v_line in
    select e->>'productId' as pid, (e->>'counted')::int as counted
      from jsonb_array_elements(p_counts) e order by 1
  loop
    if v_line.counted is null or v_line.counted < 0 then raise exception 'Conteo inválido para %', v_line.pid; end if;
    select * into v_prod from inventory where id::text = v_line.pid for update;
    if not found then raise exception 'Producto % no existe', v_line.pid; end if;
    v_diff := v_line.counted - coalesce(v_prod.quantity, 0);
    if v_diff <> 0 then
      update inventory set quantity = v_line.counted, "updatedAt" = now() where id = v_prod.id;
      insert into kardex ("productId","productName",type,quantity,concept,"user")
      values (v_prod.id, v_prod.name, case when v_diff > 0 then 'ENTRADA' else 'SALIDA' end, abs(v_diff),
              'Conteo físico' || coalesce(': ' || nullif(btrim(p_note), ''), ''), coalesce(v_user,'Sistema'));
      v_changed := v_changed + 1;
    end if;
  end loop;
  perform audit_write('STOCK_COUNT', 'inventory', null, jsonb_build_object('lines', jsonb_array_length(p_counts), 'changed', v_changed, 'note', p_note));
  return jsonb_build_object('lines', jsonb_array_length(p_counts), 'changed', v_changed);
end $$;

