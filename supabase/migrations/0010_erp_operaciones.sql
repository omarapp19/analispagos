-- 0010: operación del ERP.
--  * Auditoría (audit_log) con triggers en precios/costos de inventario y estado de facturas.
--  * Ventas: pagos mixtos, stock negativo controlado (modo sin conexión), quién vendió.
--  * Cobro de crédito atómico, devoluciones y anulaciones con reversa de stock, kardex y caja.
--  * Cierre de caja (arqueo) por método de pago.
--  * Reportes: ventas, utilidad, antigüedad de cuentas por cobrar, reposición, baja rotación, márgenes.

alter table public.client_invoices
  add column if not exists payments      jsonb,
  add column if not exists returns       jsonb not null default '[]'::jsonb,
  add column if not exists "createdBy"   text,
  add column if not exists "needsReview" boolean not null default false,
  add column if not exists "voidedAt"    timestamptz,
  add column if not exists "voidedBy"    text,
  add column if not exists "voidReason"  text;

alter table public.inventory add column if not exists "minStock" integer not null default 0;

-- ---------- Auditoría ----------
create table if not exists public.audit_log (
  id         bigint generated by default as identity primary key,
  at         timestamptz not null default now(),
  "user"     text,
  action     text not null,
  entity     text not null,
  "entityId" text,
  detail     jsonb
);
create index if not exists idx_audit_log_at on public.audit_log (at desc);
alter table public.audit_log enable row level security;
drop policy if exists "staff lee auditoria" on public.audit_log;
create policy "staff lee auditoria" on public.audit_log for select to authenticated using (is_admin());

create or replace function public.audit_write(p_action text, p_entity text, p_entity_id text, p_detail jsonb)
returns void language plpgsql security definer set search_path = public as $$
declare v_user text;
begin
  select username into v_user from staff_profiles where "userId" = auth.uid();
  insert into audit_log ("user", action, entity, "entityId", detail)
  values (coalesce(v_user, 'Sistema'), p_action, p_entity, p_entity_id, p_detail);
end $$;
revoke all on function public.audit_write(text, text, text, jsonb) from public, anon, authenticated;

create or replace function public.trg_audit_inventory() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    perform audit_write('DELETE', 'inventory', old.id::text, jsonb_build_object('name', old.name, 'code', old.code, 'quantity', old.quantity));
    return old;
  end if;
  if new."sellingPrice" is distinct from old."sellingPrice" or new."costPrice" is distinct from old."costPrice" then
    perform audit_write('PRICE_CHANGE', 'inventory', new.id::text, jsonb_build_object(
      'name', new.name,
      'sellingPrice', jsonb_build_array(old."sellingPrice", new."sellingPrice"),
      'costPrice', jsonb_build_array(old."costPrice", new."costPrice")));
  end if;
  return new;
end $$;
drop trigger if exists audit_inventory on public.inventory;
create trigger audit_inventory after update or delete on public.inventory
  for each row execute function public.trg_audit_inventory();

create or replace function public.trg_audit_invoice() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    perform audit_write('DELETE', 'client_invoices', old.id::text, jsonb_build_object('invoiceNumber', old."invoiceNumber", 'total', old.total));
    return old;
  end if;
  if new.status is distinct from old.status then
    perform audit_write('STATUS', 'client_invoices', new.id::text,
      jsonb_build_object('invoiceNumber', new."invoiceNumber", 'from', old.status, 'to', new.status, 'total', new.total));
  end if;
  return new;
end $$;
drop trigger if exists audit_invoice on public.client_invoices;
create trigger audit_invoice after update or delete on public.client_invoices
  for each row execute function public.trg_audit_invoice();

-- ---------- Venta (pagos mixtos, stock negativo controlado, vendedor) ----------
create or replace function public.erp_create_invoice(payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username   text;
  v_number     text;
  v_is_credit  boolean := coalesce((payload->>'isCredit')::boolean, false);
  v_credit_days int    := coalesce((payload->>'creditDays')::int, 0);
  v_total      numeric := coalesce((payload->>'total')::numeric, 0);
  v_subtotal   numeric := coalesce((payload->>'subtotal')::numeric, 0);
  v_date       date    := coalesce(nullif(payload->>'date','')::date, (now() at time zone 'America/Caracas')::date);
  v_method     text    := coalesce(nullif(payload->>'paymentMethod',''), 'Efectivo');
  v_client_id  text    := nullif(payload->>'clientId','');
  v_client_name text   := coalesce(payload->>'clientName','');
  v_concept    text;
  v_items      jsonb   := coalesce(payload->'items','[]'::jsonb);
  v_line       record;
  v_prod       record;
  v_reserved   int;
  v_invoice    client_invoices%rowtype;
  v_review     boolean := false;
  v_allow      boolean := coalesce((payload->>'allowNegativeStock')::boolean, false);
  v_payments   jsonb   := case when jsonb_typeof(payload->'payments') = 'array' and jsonb_array_length(payload->'payments') > 0 then payload->'payments' else null end;
  v_pay        record;
  v_paysum     numeric := 0;
begin
  if not is_staff() then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  if jsonb_typeof(v_items) <> 'array' or jsonb_array_length(v_items) = 0 then
    raise exception 'La factura no tiene productos';
  end if;
  if v_total < 0 or v_subtotal < 0 then
    raise exception 'Totales inválidos';
  end if;

  select username into v_username from staff_profiles where "userId" = auth.uid();

  if v_payments is not null and not v_is_credit then
    select coalesce(sum((p->>'amount')::numeric), 0) into v_paysum from jsonb_array_elements(v_payments) p;
    if abs(v_paysum - v_total) > 0.01 then
      raise exception 'La suma de los pagos (%) no coincide con el total (%)', v_paysum, v_total;
    end if;
    if jsonb_array_length(v_payments) > 1 then v_method := 'Mixto';
    else v_method := coalesce(nullif(v_payments->0->>'method',''), v_method); end if;
  end if;

  v_number := nullif(btrim(coalesce(payload->>'invoiceNumber','')), '');
  if v_number is null then
    v_number := 'FAC-' || lpad(nextval('invoice_seq')::text, 6, '0');
  elsif exists (select 1 from client_invoices where "invoiceNumber" = v_number) then
    raise exception 'El número de factura % ya existe', v_number;
  end if;

  v_concept := coalesce(nullif(payload->>'kardexConcept',''), 'Venta - Factura #' || v_number);

  for v_line in
    select (e->>'productId') as product_id, sum(coalesce((e->>'quantity')::int, 0)) as qty
    from jsonb_array_elements(v_items) e
    group by 1
    order by 1
  loop
    if v_line.qty <= 0 then
      raise exception 'Cantidad inválida';
    end if;

    select * into v_prod from inventory where id::text = v_line.product_id for update;
    if not found then
      raise exception 'Producto % no existe', v_line.product_id;
    end if;

    if coalesce(v_prod."productType",'product') = 'product' then
      select coalesce(sum(s.quantity), 0) into v_reserved
        from stock_reservations s
       where s."productId" = v_prod.id and not s.released and s."expiresAt" > now();

      if coalesce(v_prod.quantity,0) - v_reserved < v_line.qty and v_allow then
        v_review := true;  -- venta ya entregada (modo sin conexión): se permite stock negativo y se marca para revisión
      elsif coalesce(v_prod.quantity,0) - v_reserved < v_line.qty then
        raise exception '%', format('Sin stock suficiente para "%s": disponible %s%s, solicitado %s',
          v_prod.name, greatest(coalesce(v_prod.quantity,0) - v_reserved, 0),
          case when v_reserved > 0 then ' (' || v_reserved || ' apartados en pedidos web)' else '' end,
          v_line.qty)
          using errcode = 'P0001';
      end if;

      update inventory
         set quantity = quantity - v_line.qty, "updatedAt" = now()
       where id = v_prod.id;

      insert into kardex ("productId","productName",type,quantity,concept,"user")
      values (v_prod.id, v_prod.name, 'SALIDA', v_line.qty, v_concept, coalesce(v_username,'Sistema'));
    end if;
  end loop;

  insert into client_invoices
    ("invoiceNumber","clientId","clientName", items, subtotal, total,
     "isCredit","creditDays", status, "paymentMethod", date, payments, "createdBy", "needsReview")
  values
    (v_number, (select c.id from clients c where c.id::text = v_client_id), v_client_name, v_items, v_subtotal, v_total,
     v_is_credit, v_credit_days,
     case when v_is_credit then 'PENDING' else 'PAID' end,
     v_method, v_date, v_payments, coalesce(v_username,'Sistema'), v_review)
  returning * into v_invoice;

  if not v_is_credit then
    if v_payments is not null then
      for v_pay in select p->>'method' as method, (p->>'amount')::numeric as amount from jsonb_array_elements(v_payments) p loop
        if v_pay.amount > 0 then
          insert into transactions (amount, method, date, note, type, category, status)
          values (v_pay.amount, coalesce(nullif(v_pay.method,''),'Efectivo'), v_date,
                  'Factura ' || v_number || ' - Cliente: ' || v_client_name,
                  'INCOME', 'Venta', 'COMPLETED');
        end if;
      end loop;
    else
      insert into transactions (amount, method, date, note, type, category, status)
      values (v_total, v_method, v_date,
              'Factura ' || v_number || ' - Cliente: ' || v_client_name,
              'INCOME', 'Venta', 'COMPLETED');
    end if;
  end if;

  return to_jsonb(v_invoice);
end;
$$;

-- ---------- Cobro de una factura a crédito (atómico) ----------
create or replace function public.erp_pay_invoice(p_invoice_id text, p_method text default 'Efectivo', p_payments jsonb default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_inv client_invoices%rowtype;
  v_pay record;
  v_sum numeric := 0;
  v_method text := coalesce(nullif(p_method,''), 'Efectivo');
  v_date date := (now() at time zone 'America/Caracas')::date;
begin
  if not is_staff() then raise exception 'No autorizado' using errcode = '42501'; end if;
  select * into v_inv from client_invoices where id::text = p_invoice_id for update;
  if not found then raise exception 'Factura no encontrada'; end if;
  if v_inv.status <> 'PENDING' then raise exception 'La factura % no está pendiente de cobro (estado %)', v_inv."invoiceNumber", v_inv.status; end if;

  if p_payments is not null and jsonb_typeof(p_payments) = 'array' and jsonb_array_length(p_payments) > 0 then
    select coalesce(sum((p->>'amount')::numeric), 0) into v_sum from jsonb_array_elements(p_payments) p;
    if abs(v_sum - v_inv.total) > 0.01 then raise exception 'La suma de los pagos (%) no coincide con el total (%)', v_sum, v_inv.total; end if;
    if jsonb_array_length(p_payments) > 1 then v_method := 'Mixto'; else v_method := coalesce(nullif(p_payments->0->>'method',''), v_method); end if;
    for v_pay in select p->>'method' as method, (p->>'amount')::numeric as amount from jsonb_array_elements(p_payments) p loop
      if v_pay.amount > 0 then
        insert into transactions (amount, method, date, note, type, category, status)
        values (v_pay.amount, coalesce(nullif(v_pay.method,''),'Efectivo'), v_date,
                'Cobro Factura ' || v_inv."invoiceNumber" || ' - Cliente: ' || coalesce(v_inv."clientName",''), 'INCOME', 'Venta', 'COMPLETED');
      end if;
    end loop;
  else
    insert into transactions (amount, method, date, note, type, category, status)
    values (v_inv.total, v_method, v_date,
            'Cobro Factura ' || v_inv."invoiceNumber" || ' - Cliente: ' || coalesce(v_inv."clientName",''), 'INCOME', 'Venta', 'COMPLETED');
  end if;

  update client_invoices set status = 'PAID', "paymentMethod" = v_method,
         payments = coalesce(p_payments, payments), "updatedAt" = now()
   where id = v_inv.id returning * into v_inv;
  return to_jsonb(v_inv);
end $$;

-- ---------- Devolución parcial o anulación total ----------
-- p_items null = anular toda la factura. Si no, [{productId, quantity}] a devolver.
create or replace function public.erp_return_invoice(p_invoice_id text, p_items jsonb default null, p_reason text default null, p_refund_method text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_inv client_invoices%rowtype;
  v_username text;
  v_line record;
  v_sold int; v_ret int;
  v_prod record;
  v_ratio numeric;
  v_amount numeric := 0;
  v_price numeric;
  v_ret_items jsonb := '[]'::jsonb;
  v_full boolean := (p_items is null);
  v_all_returned boolean := true;
  v_method text;
  v_date date := (now() at time zone 'America/Caracas')::date;
begin
  if not is_admin() then raise exception 'No autorizado' using errcode = '42501'; end if;
  if coalesce(btrim(p_reason), '') = '' then raise exception 'Indica el motivo de la devolución'; end if;
  select * into v_inv from client_invoices where id::text = p_invoice_id for update;
  if not found then raise exception 'Factura no encontrada'; end if;
  if v_inv.status = 'VOIDED' then raise exception 'La factura % ya está anulada', v_inv."invoiceNumber"; end if;
  select username into v_username from staff_profiles where "userId" = auth.uid();

  if v_full then
    if jsonb_array_length(v_inv.returns) > 0 then
      raise exception 'La factura ya tiene devoluciones parciales: devuelve los productos restantes por línea';
    end if;
    select coalesce(jsonb_agg(jsonb_build_object('productId', e->>'productId', 'quantity', (e->>'quantity')::int)), '[]'::jsonb)
      into p_items from jsonb_array_elements(v_inv.items) e;
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'No hay productos a devolver'; end if;

  v_ratio := case when coalesce(v_inv.subtotal,0) > 0 then v_inv.total / v_inv.subtotal else 1 end;

  for v_line in
    select (e->>'productId') as product_id, sum((e->>'quantity')::int) as qty
    from jsonb_array_elements(p_items) e group by 1 order by 1
  loop
    if v_line.qty <= 0 then raise exception 'Cantidad inválida'; end if;
    select coalesce(sum((e->>'quantity')::int),0), coalesce(max((e->>'price')::numeric),0) into v_sold, v_price
      from jsonb_array_elements(v_inv.items) e where e->>'productId' = v_line.product_id;
    if v_sold = 0 then raise exception 'El producto % no está en la factura', v_line.product_id; end if;
    select coalesce(sum((q->>'quantity')::int),0) into v_ret
      from jsonb_array_elements(v_inv.returns) r, jsonb_array_elements(r->'items') q where q->>'productId' = v_line.product_id;
    if v_line.qty > v_sold - v_ret then
      raise exception 'Se intenta devolver % de "%", pero solo quedan % por devolver', v_line.qty, v_line.product_id, v_sold - v_ret;
    end if;

    select * into v_prod from inventory where id::text = v_line.product_id for update;
    if found and coalesce(v_prod."productType",'product') = 'product' then
      update inventory set quantity = quantity + v_line.qty, "updatedAt" = now() where id = v_prod.id;
      insert into kardex ("productId","productName",type,quantity,concept,"user")
      values (v_prod.id, v_prod.name, 'ENTRADA', v_line.qty,
              case when v_full then 'Anulación - Factura #' else 'Devolución - Factura #' end || v_inv."invoiceNumber", coalesce(v_username,'Sistema'));
    end if;
    v_amount := v_amount + round(v_line.qty * v_price * v_ratio, 2);
    v_ret_items := v_ret_items || jsonb_build_array(jsonb_build_object('productId', v_line.product_id, 'quantity', v_line.qty));
  end loop;

  -- ¿Quedó todo devuelto? (incluye esta devolución)
  select coalesce(bool_and(sold.qty <= coalesce(ret.qty, 0)), true) into v_all_returned
    from (select e->>'productId' as pid, sum((e->>'quantity')::int) as qty
            from jsonb_array_elements(v_inv.items) e group by 1) sold
    left join (select q->>'productId' as pid, sum((q->>'quantity')::int) as qty
                 from jsonb_array_elements(v_inv.returns || jsonb_build_array(jsonb_build_object('items', v_ret_items))) r,
                      jsonb_array_elements(r->'items') q group by 1) ret using (pid);

  if v_amount > v_inv.total then v_amount := v_inv.total; end if;

  -- Reembolso de caja solo si la factura estaba cobrada.
  if v_inv.status = 'PAID' and v_amount > 0 then
    v_method := coalesce(nullif(p_refund_method,''), nullif(v_inv."paymentMethod",''), 'Efectivo');
    if v_method = 'Mixto' then v_method := 'Efectivo'; end if;
    insert into transactions (amount, method, date, note, type, category, status)
    values (v_amount, v_method, v_date,
            case when v_full then 'Anulación Factura ' else 'Devolución Factura ' end || v_inv."invoiceNumber" || ' - ' || p_reason,
            'EXPENSE', 'Devolución', 'COMPLETED');
  end if;

  update client_invoices set
    returns = returns || jsonb_build_array(jsonb_build_object('at', now(), 'by', coalesce(v_username,'Sistema'),
                'reason', p_reason, 'amount', v_amount, 'items', v_ret_items)),
    status = case when v_all_returned then 'VOIDED' else status end,
    "voidedAt" = case when v_all_returned then now() else "voidedAt" end,
    "voidedBy" = case when v_all_returned then coalesce(v_username,'Sistema') else "voidedBy" end,
    "voidReason" = case when v_all_returned then p_reason else "voidReason" end,
    "updatedAt" = now()
  where id = v_inv.id returning * into v_inv;

  perform audit_write(case when v_full then 'VOID' else 'RETURN' end, 'client_invoices', v_inv.id::text,
    jsonb_build_object('invoiceNumber', v_inv."invoiceNumber", 'amount', v_amount, 'reason', p_reason, 'items', v_ret_items));
  return to_jsonb(v_inv);
end $$;

-- ---------- Cierre de caja ----------
create table if not exists public.cash_sessions (
  id             text primary key default gen_random_uuid()::text,
  "openedAt"     timestamptz not null default now(),
  "openedBy"     text,
  "openingFloat" numeric not null default 0,
  status         text not null default 'OPEN',
  "closedAt"     timestamptz,
  "closedBy"     text,
  expected       jsonb,
  counted        jsonb,
  difference     numeric,
  notes          text
);
create unique index if not exists one_open_cash_session on public.cash_sessions (status) where status = 'OPEN';
alter table public.cash_sessions enable row level security;
drop policy if exists "staff lee caja" on public.cash_sessions;
create policy "staff lee caja" on public.cash_sessions for select to authenticated using (is_staff());

-- Esperado por método: ingresos - egresos de transacciones completadas desde la apertura (+ fondo en Efectivo).
create or replace function public.cash_expected(p_session cash_sessions)
returns jsonb language sql stable security definer set search_path = public as $$
  with m as (
    select coalesce(nullif(method,''),'Efectivo') as method,
           sum(case when type = 'INCOME' then amount else -amount end) as net
      from transactions
     where "createdAt" >= p_session."openedAt" and coalesce(status,'COMPLETED') = 'COMPLETED'
       and (p_session."closedAt" is null or "createdAt" <= p_session."closedAt")
     group by 1
  ), allm as (
    select method, net from m
    union all select 'Efectivo', 0 where not exists (select 1 from m where method = 'Efectivo')
  )
  select coalesce(jsonb_object_agg(method, round(net + case when method = 'Efectivo' then p_session."openingFloat" else 0 end, 2)), '{}'::jsonb) from allm
$$;
revoke all on function public.cash_expected(cash_sessions) from public, anon, authenticated;

create or replace function public.cash_current() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v cash_sessions%rowtype;
begin
  if not is_staff() then raise exception 'No autorizado' using errcode = '42501'; end if;
  select * into v from cash_sessions where status = 'OPEN';
  if not found then return null; end if;
  return to_jsonb(v) || jsonb_build_object('expected', cash_expected(v));
end $$;

create or replace function public.cash_open(p_float numeric default 0, p_notes text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v cash_sessions%rowtype; v_user text;
begin
  if not is_staff() then raise exception 'No autorizado' using errcode = '42501'; end if;
  if coalesce(p_float,0) < 0 then raise exception 'Fondo inválido'; end if;
  if exists (select 1 from cash_sessions where status = 'OPEN') then raise exception 'Ya hay una caja abierta'; end if;
  select username into v_user from staff_profiles where "userId" = auth.uid();
  insert into cash_sessions ("openedBy","openingFloat",notes) values (coalesce(v_user,'Sistema'), coalesce(p_float,0), p_notes) returning * into v;
  perform audit_write('CASH_OPEN', 'cash_sessions', v.id, jsonb_build_object('float', v."openingFloat"));
  return to_jsonb(v);
end $$;

-- p_counted: {"Efectivo": 120.5, "Transferencia": 80}
create or replace function public.cash_close(p_counted jsonb, p_notes text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v cash_sessions%rowtype; v_user text; v_exp jsonb; v_diff numeric := 0; k text;
begin
  if not is_staff() then raise exception 'No autorizado' using errcode = '42501'; end if;
  if p_counted is null or jsonb_typeof(p_counted) <> 'object' then raise exception 'Indica lo contado por método de pago'; end if;
  select * into v from cash_sessions where status = 'OPEN' for update;
  if not found then raise exception 'No hay caja abierta'; end if;
  select username into v_user from staff_profiles where "userId" = auth.uid();
  v.status := 'CLOSED'; v."closedAt" := now();
  v_exp := cash_expected(v);
  for k in select jsonb_object_keys(v_exp || p_counted) loop
    v_diff := v_diff + coalesce((p_counted->>k)::numeric, 0) - coalesce((v_exp->>k)::numeric, 0);
  end loop;
  update cash_sessions set status = 'CLOSED', "closedAt" = v."closedAt", "closedBy" = coalesce(v_user,'Sistema'),
         expected = v_exp, counted = p_counted, difference = round(v_diff, 2), notes = coalesce(p_notes, notes)
   where id = v.id returning * into v;
  perform audit_write('CASH_CLOSE', 'cash_sessions', v.id, jsonb_build_object('difference', v.difference, 'expected', v_exp, 'counted', p_counted));
  return to_jsonb(v);
end $$;

-- ---------- Reportes ----------
create or replace function public.report_sales(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  if not is_admin() then raise exception 'No autorizado' using errcode = '42501'; end if;
  with inv as (
    select * from client_invoices
     where status <> 'VOIDED' and "date"::date between p_from and p_to
  ), lines as (
    select i.id as inv_id, e->>'productId' as pid, e->>'name' as pname,
           greatest((e->>'quantity')::numeric - coalesce((
             select sum((q->>'quantity')::numeric) from jsonb_array_elements(i.returns) r, jsonb_array_elements(r->'items') q
              where q->>'productId' = e->>'productId'), 0), 0) as qty,
           (e->>'price')::numeric as price,
           case when coalesce(i.subtotal,0) > 0 then i.total / i.subtotal else 1 end as ratio
      from inv i, jsonb_array_elements(i.items) e
  ), prod as (
    select l.pid, max(l.pname) as name, sum(l.qty) as qty,
           round(sum(l.qty * l.price * l.ratio), 2) as revenue,
           round(sum(l.qty * coalesce(p."costPrice", 0)), 2) as cost
      from lines l left join inventory p on p.id::text = l.pid group by l.pid
  )
  select jsonb_build_object(
    'summary', (select jsonb_build_object('count', count(*), 'total', coalesce(sum(total),0)) from inv),
    'byDay', coalesce((select jsonb_agg(x order by x.date) from (select "date"::date as date, count(*) as count, round(sum(total),2) as total from inv group by 1) x), '[]'),
    'byProduct', coalesce((select jsonb_agg(x order by x.revenue desc) from (select pid as "productId", name, qty, revenue, cost, round(revenue - cost, 2) as profit from prod where qty > 0 order by revenue desc limit 50) x), '[]'),
    'byClient', coalesce((select jsonb_agg(x order by x.total desc) from (select coalesce("clientName",'Consumidor final') as client, count(*) as count, round(sum(total),2) as total from inv group by 1 order by 3 desc limit 30) x), '[]'),
    'bySeller', coalesce((select jsonb_agg(x order by x.total desc) from (select coalesce("createdBy",'(sin dato)') as seller, count(*) as count, round(sum(total),2) as total from inv group by 1) x), '[]'),
    'profit', (select jsonb_build_object('revenue', coalesce(sum(revenue),0), 'cost', coalesce(sum(cost),0), 'profit', coalesce(sum(revenue - cost),0)) from prod)
  ) into v;
  return v;
end $$;

create or replace function public.report_receivables_aging() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v jsonb; v_today date := (now() at time zone 'America/Caracas')::date;
begin
  if not is_admin() then raise exception 'No autorizado' using errcode = '42501'; end if;
  select coalesce(jsonb_agg(x order by x."daysOverdue" desc), '[]') into v from (
    select id::text as id, "invoiceNumber", "clientId"::text as "clientId", "clientName", total,
           ("date"::date + coalesce("creditDays",0)) as "dueDate",
           greatest(v_today - ("date"::date + coalesce("creditDays",0)), 0) as "daysOverdue",
           case when v_today <= ("date"::date + coalesce("creditDays",0)) then 'Vigente'
                when v_today - ("date"::date + coalesce("creditDays",0)) <= 30 then '1-30'
                when v_today - ("date"::date + coalesce("creditDays",0)) <= 60 then '31-60'
                else '60+' end as bucket
      from client_invoices where status = 'PENDING') x;
  return v;
end $$;

-- Reposición: bajo mínimo o con pocos días de cobertura según lo vendido en p_days.
create or replace function public.report_restock(p_days int default 30) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  if not is_admin() then raise exception 'No autorizado' using errcode = '42501'; end if;
  select coalesce(jsonb_agg(x order by x."coverageDays" nulls last, x.name), '[]') into v from (
    select p.id::text as id, p.code, p.name, p.quantity, p."minStock",
           coalesce(s.sold, 0) as sold,
           round(coalesce(s.sold, 0)::numeric / greatest(p_days, 1), 2) as "dailyRate",
           case when coalesce(s.sold,0) > 0 then round(greatest(p.quantity,0) / (s.sold::numeric / greatest(p_days,1)), 1) end as "coverageDays",
           greatest(ceil(coalesce(s.sold,0)::numeric / greatest(p_days,1) * 30)::int - greatest(p.quantity,0), coalesce(p."minStock",0) - greatest(p.quantity,0), 0) as suggested
      from inventory p
      left join (
        select e->>'productId' as pid, sum((e->>'quantity')::numeric)::int as sold
          from client_invoices i, jsonb_array_elements(i.items) e
         where i.status <> 'VOIDED' and i."createdAt" >= now() - make_interval(days => greatest(p_days,1))
         group by 1) s on s.pid = p.id::text
     where coalesce(p."productType",'product') = 'product'
       and (p.quantity <= coalesce(p."minStock",0) or (coalesce(s.sold,0) > 0 and p.quantity / (s.sold::numeric / greatest(p_days,1)) < 15))
  ) x;
  return v;
end $$;

-- Baja rotación: con existencia y sin ventas en p_days. Dinero inmovilizado = existencia x costo.
create or replace function public.report_slow_movers(p_days int default 90) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  if not is_admin() then raise exception 'No autorizado' using errcode = '42501'; end if;
  select coalesce(jsonb_agg(x order by x."tiedCapital" desc), '[]') into v from (
    select p.id::text as id, p.code, p.name, p.quantity, coalesce(p."costPrice",0) as "costPrice",
           round(p.quantity * coalesce(p."costPrice",0), 2) as "tiedCapital"
      from inventory p
     where coalesce(p."productType",'product') = 'product' and p.quantity > 0
       and not exists (
         select 1 from client_invoices i, jsonb_array_elements(i.items) e
          where i.status <> 'VOIDED' and i."createdAt" >= now() - make_interval(days => greatest(p_days,1))
            and e->>'productId' = p.id::text)
     order by 6 desc limit 100) x;
  return v;
end $$;

-- Productos con precio bajo el costo o con margen menor al mínimo.
create or replace function public.report_margin_alerts(p_min_pct numeric default 10) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  if not is_admin() then raise exception 'No autorizado' using errcode = '42501'; end if;
  select coalesce(jsonb_agg(x order by x."marginPct"), '[]') into v from (
    select p.id::text as id, p.code, p.name, p."costPrice", p."sellingPrice",
           round((p."sellingPrice" - p."costPrice") / nullif(p."costPrice",0) * 100, 1) as "marginPct"
      from inventory p
     where coalesce(p."productType",'product') = 'product' and coalesce(p."costPrice",0) > 0
       and (p."sellingPrice" - p."costPrice") / p."costPrice" * 100 < p_min_pct) x;
  return v;
end $$;

